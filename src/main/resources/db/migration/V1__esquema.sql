CREATE TABLE marca (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE categoria (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE producto (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(200)  NOT NULL,
    descripcion         VARCHAR(2000),
    ingredientes        VARCHAR(2000),
    modo_uso            VARCHAR(1000),
    precio              NUMERIC(12,2) NOT NULL,
    stock               INTEGER       NOT NULL DEFAULT 0,
    url_imagen          VARCHAR(500),
    fuente_imagen       VARCHAR(300),
    tipo_piel           VARCHAR(50),
    etiquetas           VARCHAR(300),
    mas_vendido         BOOLEAN       NOT NULL DEFAULT FALSE,
    fecha_actualizacion DATE          NOT NULL,
    marca_id            BIGINT        NOT NULL REFERENCES marca(id),
    categoria_id        BIGINT        NOT NULL REFERENCES categoria(id)
);

CREATE INDEX idx_producto_marca     ON producto(marca_id);
CREATE INDEX idx_producto_categoria ON producto(categoria_id);

CREATE TABLE usuario (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(120) NOT NULL,
    email     VARCHAR(160) NOT NULL UNIQUE,
    password  VARCHAR(100) NOT NULL,
    rol       VARCHAR(20)  NOT NULL
);

CREATE TABLE pedido (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          BIGINT        NOT NULL REFERENCES usuario(id),
    fecha               TIMESTAMP     NOT NULL,
    nombre_destinatario VARCHAR(120)  NOT NULL,
    telefono            VARCHAR(30)   NOT NULL,
    departamento        VARCHAR(80)   NOT NULL,
    ciudad              VARCHAR(80)   NOT NULL,
    direccion           VARCHAR(200)  NOT NULL,
    metodo_pago         VARCHAR(30)   NOT NULL,
    subtotal            NUMERIC(12,2) NOT NULL,
    envio               NUMERIC(12,2) NOT NULL,
    total               NUMERIC(12,2) NOT NULL,
    estado              VARCHAR(30)   NOT NULL
);

CREATE TABLE item_pedido (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT        NOT NULL REFERENCES pedido(id),
    producto_id      BIGINT        NOT NULL REFERENCES producto(id),
    nombre_producto  VARCHAR(200)  NOT NULL,
    precio_unitario  NUMERIC(12,2) NOT NULL,
    cantidad         INTEGER       NOT NULL
);
